import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint, DateTime, ForeignKey, Index, Integer, Numeric, SmallInteger, String, Text, Uuid, func, text,
)
from sqlalchemy.dialects.postgresql import CHAR, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

CAPTURE_SOURCES = ("device", "phone")
WEIGHT_SOURCES = ("measured", "user_estimate")
CAPTURE_STATUSES = ("identifying", "awaiting_weight", "needs_review", "logged", "discarded", "failed")
IMAGE_STATUSES = ("local", "uploaded", "upload_failed")
RUN_STATUSES = ("running", "succeeded", "failed", "rate_limited")
RUN_DECISIONS = ("auto_logged", "needs_review")


class Capture(Base):
    """One photo (+ weight). `id` is generated by the device or app, which makes retries idempotent."""

    __tablename__ = "captures"
    __table_args__ = (
        CheckConstraint("source IN ('device', 'phone')", name="ck_captures_source"),
        CheckConstraint("weight_source IN ('measured', 'user_estimate')", name="ck_captures_weight_source"),
        CheckConstraint(
            "status IN ('identifying', 'awaiting_weight', 'needs_review', 'logged', 'discarded', 'failed')",
            name="ck_captures_status",
        ),
        CheckConstraint("image_status IN ('local', 'uploaded', 'upload_failed')", name="ck_captures_image_status"),
        CheckConstraint(
            "(source = 'device' AND device_id IS NOT NULL AND weight_source = 'measured' AND weight_g IS NOT NULL)"
            " OR (source = 'phone' AND device_id IS NULL AND weight_source = 'user_estimate')",
            name="ck_captures_source_rules",
        ),
        CheckConstraint("weight_g IS NULL OR weight_g > 0", name="ck_captures_weight_positive"),
        Index("ix_captures_user_received", "user_id", text("received_at DESC")),
        Index(
            "ix_captures_user_open_status", "user_id", "status",
            postgresql_where=text("status IN ('identifying', 'awaiting_weight', 'needs_review')"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    source: Mapped[str] = mapped_column(String)
    device_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("devices.id"))
    weight_g: Mapped[float | None] = mapped_column(Numeric(7, 1))
    weight_source: Mapped[str] = mapped_column(String)
    status: Mapped[str] = mapped_column(String)
    selected_food_id: Mapped[int | None] = mapped_column(ForeignKey("foods.id"))
    not_in_catalog_label: Mapped[str | None] = mapped_column(Text)
    image_status: Mapped[str] = mapped_column(String)
    image_local_path: Mapped[str | None] = mapped_column(Text)
    image_url: Mapped[str | None] = mapped_column(Text)
    image_public_id: Mapped[str | None] = mapped_column(Text)
    image_bytes: Mapped[int] = mapped_column(Integer)
    image_sha256: Mapped[str] = mapped_column(CHAR(64))
    captured_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    received_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    recognized_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
    firmware_version: Mapped[str | None] = mapped_column(Text)
    app_version: Mapped[str | None] = mapped_column(Text)

    runs: Mapped[list["RecognitionRun"]] = relationship(
        cascade="all, delete-orphan", passive_deletes=True, order_by="RecognitionRun.attempt"
    )


class RecognitionRun(Base):
    __tablename__ = "recognition_runs"
    __table_args__ = (
        CheckConstraint(
            "status IN ('running', 'succeeded', 'failed', 'rate_limited')", name="ck_recognition_runs_status"
        ),
        CheckConstraint(
            "decision IS NULL OR decision IN ('auto_logged', 'needs_review')", name="ck_recognition_runs_decision"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    capture_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("captures.id", ondelete="CASCADE"), index=True)
    attempt: Mapped[int] = mapped_column(SmallInteger)
    provider: Mapped[str] = mapped_column(Text)
    model: Mapped[str] = mapped_column(Text)
    prompt_version: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String)
    decision: Mapped[str | None] = mapped_column(String)
    top_confidence: Mapped[float | None] = mapped_column(Numeric(4, 3))
    latency_ms: Mapped[int | None] = mapped_column(Integer)
    input_tokens: Mapped[int | None] = mapped_column(Integer)
    output_tokens: Mapped[int | None] = mapped_column(Integer)
    error_code: Mapped[str | None] = mapped_column(Text)
    error_message: Mapped[str | None] = mapped_column(Text)
    raw_response: Mapped[dict | None] = mapped_column(JSONB)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    candidates: Mapped[list["RecognitionCandidate"]] = relationship(
        cascade="all, delete-orphan", passive_deletes=True, order_by="RecognitionCandidate.rank", lazy="selectin"
    )


class RecognitionCandidate(Base):
    __tablename__ = "recognition_candidates"

    run_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("recognition_runs.id", ondelete="CASCADE"), primary_key=True)
    rank: Mapped[int] = mapped_column(SmallInteger, primary_key=True)
    returned_code: Mapped[str] = mapped_column(Text)
    food_id: Mapped[int | None] = mapped_column(ForeignKey("foods.id"))
    confidence: Mapped[float] = mapped_column(Numeric(4, 3))
